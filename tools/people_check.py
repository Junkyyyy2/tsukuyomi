import datetime as dt
SYN = 29.530588853
REF = dt.datetime(2000, 1, 6, 18, 14)  # 基準の新月（UTC）
def moon_age(y, m, d):
    t = dt.datetime(y, m, d, 3, 0)  # 日本時間の正午
    return ((t - REF).total_seconds() / 86400) % SYN
def element(m, d):
    md = m * 100 + d
    signs = [(120, "W"), (219, "S"), (321, "W"), (420, "S"), (521, "W"), (622, "S"), (723, "W"), (823, "S"), (923, "W"), (1024, "S"), (1123, "W"), (1222, "S")]
    # 山羊(地)1/1-1/19, 水瓶(風)1/20-, 魚(水)2/19-, 牡羊(火)3/21-, 牡牛(地)4/20-, 双子(風)5/21-, 蟹(水)6/22-, 獅子(火)7/23-, 乙女(地)8/23-, 天秤(風)9/23-, 蠍(水)10/24-, 射手(火)11/23-, 山羊12/22-
    table = [(101, "W"), (120, "S"), (219, "W"), (321, "S"), (420, "W"), (521, "S"), (622, "W"), (723, "S"), (823, "W"), (923, "S"), (1024, "W"), (1123, "S"), (1222, "W")]
    e = "W"
    for start, v in table:
        if md >= start:
            e = v
    return e
def sun(m, d):
    md = m * 100 + d
    return "A" if (md >= 1222 or md <= 621) else "D"
def star_type(y, m, d):
    a = moon_age(y, m, d)
    c = "C" if a < SYN / 2 else "R"
    f = "F" if abs(a - SYN / 2) < SYN / 4 else "N"
    return c + f + element(m, d) + sun(m, d)
